function result = equipment_sizing(modelInput,request,options)
%EQUIPMENT_SIZING Calculate two explicitly illustrative Prompt 17 screening checks.
% HX area: A=Q/(U*F*LMTD). Pump: P_shaft=rho*g*Qv*H/eta.
% Inputs and equations use W, kg/s, m3/s, Pa and SI geometry. No code-level
% vessel, reactor, relief, compressor or vendor design is implied.
narginchk(3,3);
energy=energy008.get_option(request,'energy_result',struct());
material=energy008.get_option(request,'material_result',struct());
if ~isfield(energy,'value') || ~isfield(material,'value') || ~isfield(material.value,'SI_flows')
    msg='Equipment screening requires reference energy and SI material-flow results.';
    result=energy008.make_result('equipment_sizing','BLOCKED',struct('blockers',{{msg}}),'N/A',modelInput,{msg},{},struct(),struct()); return;
end
ass=modelInput.properties.screening_assumptions;
hx=ass.heat_exchanger; pump=ass.water_pump;
Q_W=energy.value.co2_sensible_heating.duty_kW*1000;
area=Q_W/(hx.overall_U_W_m2_K*hx.correction_factor*hx.lmtd_K);
mdot_kg_s=material.value.SI_flows.mass_flows_kg_s.electrolyser_water_kg_s;
Qv_m3_s=mdot_kg_s/pump.density_kg_m3;
P_W=pump.density_kg_m3*pump.gravity_m_s2*Qv_m3_s*pump.head_m/pump.efficiency;
P_kW=P_W/1000; mdot_kg_h=mdot_kg_s*3600; Qv_m3_h=Qv_m3_s*3600;
flowMargin=1+pump.flow_margin_fraction; P_margin=P_kW*flowMargin;
eq=modelInput.equipment_register.equipment;
eqIds={eq.equipment_id}'; eqTypes={eq.equipment_type}'; eqServices={eq.service}'; eqStatuses={eq.data_status}';
missingInputs=cell(numel(eq),1); for q=1:numel(eq), missingInputs{q}=strjoin(eq(q).required_inputs,'; '); end
datasheetTable=table(eqIds,eqTypes,eqServices,eqStatuses,missingInputs,'VariableNames',{'Equipment_ID','Equipment_Type','Service','Data_Status','Required_Inputs'});
values=struct('datasheet_register',datasheetTable,'equipment_count',numel(eq), ...
 'HX_example',struct('equipment_id','HX-A01','heat_duty_kW',Q_W/1000, ...
    'U_W_m2_K',hx.overall_U_W_m2_K,'F',hx.correction_factor,'LMTD_K',hx.lmtd_K, ...
    'area_m2',area,'status','SCREENING_ONLY','source_id',hx.source_id), ...
 'W201_pump_example',struct('equipment_id','W-201','water_mass_flow_kg_s',mdot_kg_s, ...
    'water_mass_flow_kg_h',mdot_kg_h,'density_kg_m3',pump.density_kg_m3, ...
    'volumetric_flow_m3_s',Qv_m3_s,'volumetric_flow_m3_h',Qv_m3_h, ...
    'head_m',pump.head_m,'efficiency',pump.efficiency,'shaft_power_kW',P_kW, ...
    'flow_margin_fraction',pump.flow_margin_fraction,'flow_with_margin_m3_h',Qv_m3_h*flowMargin, ...
    'power_with_margin_kW',P_margin,'status','SCREENING_ONLY','source_id',pump.source_id), ...
 'other_major_equipment',struct('status','BLOCKED','items',{{'R-301 PFR volume/catalyst mass','K-101/K-201/K-301 compressor power','V-101/V-301/V-302/T-401 vessel/column sizing','relief and mechanical code design'}}, ...
    'reason','Kinetic constants, real-gas states, mixture properties, vendor maps, dimensions, pressure drops and code design basis are unavailable.'));
warn={'These equations reproduce Prompt 17 arithmetic checks only; they do not size or rate HX-301 or the actual W-201 package.'; ...
      'No mechanical code thickness, relief sizing, nozzle, metallurgy or vendor performance is included.'};
result=energy008.make_result('equipment_sizing','SCREENING_ONLY',values,struct('area','m2','flow','m3/h (display); m3/s (internal)','power','kW'),modelInput,warn,{}, ...
    struct('HX_area_m2',area,'W201_pump_power_kW',P_kW),struct('source_ids',{{hx.source_id,pump.source_id}}));
end
