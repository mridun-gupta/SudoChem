function result = utilities_model(modelInput,request,options)
%UTILITIES_MODEL Compute stoichiometric water/O2 references; block utility performance.
narginchk(3,3);
material=energy008.get_option(request,'material_result',struct());
if ~isfield(material,'value')
    msg='Utility screening requires material-balance outputs.';
    result=energy008.make_result('utilities_model','BLOCKED',struct('blockers',{{msg}}),'N/A',modelInput,{msg},{},struct(),struct()); return;
end
mf=material.value.mass_flows;
u=modelInput.utility_register.utility_systems;
uids={u.utility_id}'; utypes={u.utility_type}'; usvc={u.service}'; ust={u.data_status}';
utable=table(uids,utypes,usvc,ust,'VariableNames',{'Utility_ID','Utility_Type','Service','Data_Status'});
values=struct('utility_register',utable,'water',struct('electrolyser_DI_water_lower_bound_kg_day',mf.electrolyser_water_kg_day, ...
    'reaction_water_formed_kg_day',mf.reaction_water_kg_day,'net_chemical_water_consumption_kg_day',mf.net_water_kg_day, ...
    'status','REFERENCE_ONLY','note','Stoichiometric DI-water lower bound excludes treatment reject, cooling water, wash water and other plant uses.'), ...
    'oxygen',struct('theoretical_coproduct_kg_day',mf.O2_kg_day,'status','REFERENCE_ONLY','note','No O2 purification, sale, vent or disposition credit assumed.'), ...
    'electricity',struct('electrolyser_electricity_kWh_day',[],'plant_electricity_kWh_day',[],'status','BLOCKED', ...
    'reason','No ALK vendor polarization/performance map, rectifier efficiency, BOP loads, compressor/pump maps or site load list.'), ...
    'cooling_and_steam',struct('cooling_duty_kW',[],'steam_duty_kW',[],'status','BLOCKED', ...
    'reason','No validated process duties or utility supply/return states.'), ...
    'emissions',struct('CO2e_kg_day',[],'kg_CO2e_per_kg_MeOH',[],'status','BLOCKED', ...
    'input_record',modelInput.environmental_basis.inputs, ...
    'reason','No metered renewable electricity profile, site/year grid factor, source emissions or approved MMRV boundary.'));
warn={'Theoretical O2 is not credited as a saleable product or avoided-emissions benefit.'; ...
      'No generic electricity consumption, utility tariff or grid emission factor is inserted.'};
result=energy008.make_result('utilities_model','BLOCKED',values,struct('water','kg/day','oxygen','kg/day','electricity','kWh/day','emissions','kg CO2e/day'),modelInput,warn,{},struct(), ...
    struct('source_ids',{{'DB-026','DB-027','DB-028','DB-059','DB-062','DB-064'}}));
end
