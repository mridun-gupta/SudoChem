function result = energy_balance(modelInput,request,options)
%ENERGY_BALANCE Calculate sourced standard-state references using SI mol/s and kW.
% No reactor cooling duty, plant energy closure or distillation duty is inferred.
narginchk(3,3);
material=energy008.get_option(request,'material_result',struct());
property=energy008.get_option(request,'property_result',struct());
if ~isfield(material,'status') || any(strcmp(material.status,{'BLOCKED','FAILED','NOT_RUN'})) || ...
        ~isfield(material,'value') || ~isfield(material.value,'reaction_extents_SI_mol_s')
    msg='Energy references require a successful SI stoichiometric material reference.';
    result=energy008.make_result('energy_balance','BLOCKED',struct('blockers',{{msg}}),'N/A',modelInput,{msg},{},struct(),struct()); return;
end
if ~isfield(property,'value') || ~isfield(property.value,'co2_sensible') || ~isfield(property.value,'methanol_latent')
    msg='Required pure-component reference properties are missing or blocked.';
    result=energy008.make_result('energy_balance','BLOCKED',struct('blockers',{{msg}}),'N/A',modelInput,{msg},{},struct(),struct()); return;
end
xi=material.value.reaction_extents_SI_mol_s;
if xi.R02>1e-12
    msg='R-02 extent is nonzero, but a source-supported R-02 reaction enthalpy and state-consistent heat-capacity data are unavailable.';
    d=energy008.diagnostic('ENERGY-R02-THERMOCHEMISTRY-MISSING','WARNING','energy_balance',msg, ...
        struct('R02_extent_mol_s',xi.R02),{'ENERGY008-DATA-0.1.0','RXN-002'}, ...
        'Obtain source-supported R-02 thermochemistry and compatible gas-phase sensible enthalpy data before calculating this energy reference.');
    result=energy008.make_result('energy_balance','BLOCKED',struct('blockers',{{msg}}),'N/A',modelInput,{msg},{},struct(), ...
        struct('source_ids',{{'ENERGY008-DATA-0.1.0','RXN-002'}})); result.diagnostics=d; return;
end
nMeOH=material.value.SI_flows.molar_flows_mol_s.CH3OH;
thermo=modelInput.properties.reaction_thermochemistry;
iR=find(strcmp({thermo.reaction_id},'R-01'),1);
iE=find(strcmp({thermo.reaction_id},'E-01'),1);
iN=find(strcmp({thermo.reaction_id},'NET-01'),1);
if isempty(iR)||isempty(iE)||isempty(iN)
    msg='Required R-01, E-01 and NET-01 standard reaction enthalpy records are missing.';
    result=energy008.make_result('energy_balance','BLOCKED',struct('blockers',{{msg}}),'N/A',modelInput,{msg},{},struct(),struct()); return;
end
H_R01=thermo(iR).delta_h_kJ_mol_reaction;
H_E01=thermo(iE).delta_h_kJ_mol_reaction;
H_NET=thermo(iN).delta_h_kJ_mol_reaction;
uncertaintyFields={'uncertainty_kJ_mol_reaction'};
for u=1:numel(uncertaintyFields)
    uf=uncertaintyFields{u};
    if ~isfield(thermo(iR),uf) || ~isfield(thermo(iE),uf) || ~isfield(thermo(iN),uf) || ...
            any(~isfinite([thermo(iR).(uf),thermo(iE).(uf),thermo(iN).(uf)])) || ...
            any([thermo(iR).(uf),thermo(iE).(uf),thermo(iN).(uf)]<0)
        error('ENERGY008:ReactionEnthalpyUncertaintyMissing','Source uncertainty for R-01/E-01/NET-01 must be finite and nonnegative.');
    end
end
sigma_R01=thermo(iR).uncertainty_kJ_mol_reaction;
sigma_E01=thermo(iE).uncertainty_kJ_mol_reaction;
sigma_NET=thermo(iN).uncertainty_kJ_mol_reaction;
% kJ/mol * mol/s = kJ/s = kW.
R01_kW=xi.R01*H_R01;
E01_kW=xi.E01*H_E01;
NET_kW=nMeOH*H_NET;
secondsPerDay=86400; kW_to_GJ_day=secondsPerDay/1e6;
electrolysisExtentPerR01=xi.E01/xi.R01;
identity=H_R01+electrolysisExtentPerR01*H_E01;
% Source-propagated enthalpy-property uncertainty only. No uncertainty in
% throughput/extent or covariance matrix is included; this is not a CI.
uncertainty=struct('status','SOURCE_PROPAGATED_SCREENING', ...
    'R01_delta_h_sigma_kJ_mol',sigma_R01,'R01_rate_sigma_kW',abs(xi.R01)*sigma_R01, ...
    'R01_rate_sigma_GJ_day',abs(xi.R01)*sigma_R01*kW_to_GJ_day, ...
    'E01_delta_h_sigma_kJ_mol',sigma_E01,'E01_rate_sigma_kW',abs(xi.E01)*sigma_E01, ...
    'E01_rate_sigma_GJ_day',abs(xi.E01)*sigma_E01*kW_to_GJ_day, ...
    'net_delta_h_sigma_kJ_mol',sigma_NET,'net_rate_sigma_kW',abs(nMeOH)*sigma_NET, ...
    'net_rate_sigma_GJ_day',abs(nMeOH)*sigma_NET*kW_to_GJ_day, ...
    'interpretation','Source-propagated enthalpy-record uncertainty only; does not include throughput, model-form or covariance uncertainty and is not a statistical confidence interval.');
sensible=property.value.co2_sensible;
latent=property.value.methanol_latent;
values=struct('reaction_reference',struct('R01_delta_h_kJ_mol',H_R01,'R01_rate_kW',R01_kW, ...
    'R01_rate_GJ_day',R01_kW*kW_to_GJ_day,'E01_delta_h_kJ_mol_reaction',H_E01, ...
    'E01_rate_kW',E01_kW,'E01_rate_GJ_day',E01_kW*kW_to_GJ_day, ...
    'net_delta_h_kJ_mol_MeOH',H_NET,'net_rate_kW',NET_kW,'net_rate_GJ_day',NET_kW*kW_to_GJ_day, ...
    'R01_plus_electrolysis_kJ_mol',identity,'E01_extent_per_R01_extent',electrolysisExtentPerR01, ...
    'identity_residual_kJ_mol',identity-H_NET, ...
    'reference_state_T_K',thermo(iR).temperature_K,'reference_state_P_Pa_abs',thermo(iR).pressure_MPa_abs*1e6,'status','REFERENCE_ONLY'), ...
    'reaction_reference_uncertainty',uncertainty, ...
    'co2_sensible_heating',sensible,'methanol_latent_reference',latent, ...
    'plant_energy_closure',struct('status','BLOCKED','value',[],'reason','Physical stream enthalpies, validated high-pressure mixture properties, equipment duties and utility states are unavailable.'), ...
    'reactor_cooling_duty',struct('status','BLOCKED','value',[],'reason','Liquid standard-state reaction enthalpy is not a gas-phase R-301 cooling duty.'), ...
    'distillation_duties',struct('status','BLOCKED','value',[],'reason','Column pressure, composition, reflux, VLE and enthalpy data are unavailable.'));
warn={'Standard-state reaction enthalpy is a reference quantity, not an equipment duty.'; ...
      'CO2 sensible duty is a pure ideal-gas Shomate reference, not the 7 MPa process heater duty.'; ...
      'Methanol latent duty is a pure-component saturation illustration, not a T-401/E-401/E-402 duty.'};
result=energy008.make_result('energy_balance','SCREENING_ONLY',values, ...
    struct('enthalpy','kJ/mol; kW; GJ/day','duty','kW'),modelInput,warn,{}, ...
    struct('reaction_enthalpy_identity_residual_kJ_mol',identity-H_NET), ...
    struct('source_ids',{{'RXN-001','E-01','NET-RXN','SHOMATE-04','DHVAP-MEOH-01'}}));
end
