function S = cps22_run_sensitivities(cfg, dataFile)
% Five independent sensitivity groups. Reference-driven studies are explicitly not
% predictive NRTL-SRK sensitivities until the model has passed Phase 2 acceptance.
if nargin<2, dataFile=cfg.paths.reference_data_abs; end
rows=struct('study_id',{},'varied_variable',{},'varied_value',{},'varied_unit',{}, ...
    'T_K',{},'P_Pa',{},'z_ethanol',{},'feed_flow_kmol_h',{},'beta',{}, ...
    'x_ethanol',{},'y_ethanol',{},'L_kmol_h',{},'V_kmol_h',{},'response_metric',{}, ...
    'response_value',{},'response_unit',{},'status',{},'notes',{});
% S1: temperature sweep over measured 1.5 MPa reference isobar.
for T=[443.5 444.0 444.5 445.0 445.5 446.0 446.5]
    c=cfg; c.conditions.temperature_K=T; r=cps22_reference_flash(c,dataFile);
    rows(end+1)=rowFromRef('S1_TEMPERATURE','temperature_K',T,'K',c,r,'vapour_fraction',r.beta,'-', ...
        'Reference interpolation only; no NRTL-SRK model prediction.'); %#ok<AGROW>
end
% S2: pressure at literature-supported isobars; no unmeasured isobar interpolation.
for P=[1.5e6 2.0e6]
    c=cfg; c.conditions.pressure_Pa=P; r=cps22_reference_flash(c,dataFile);
    pressureRow = rowFromRef('S2_PRESSURE','pressure_Pa',P,'Pa',c,r,'phase_fraction',r.beta,'-', ...
        'Only measured 1.5 and 2.0 MPa isobars considered; temperature held at base T.');
    if ~isfinite(r.beta)
        pressureRow.status = 'BLOCKED_PRESSURE_SENSITIVITY_NO_ISOTHERM_DATA';
        pressureRow.notes = ['No measured tie-line covers T=' num2str(c.conditions.temperature_K,12) ...
            ' K at P=' num2str(P/1e6,6) ' MPa; underlying reference status=' char(r.status) ...
            '. No extrapolation is allowed, so this point is not a valid pressure-sensitivity response.'];
    end
    rows(end+1)=pressureRow; %#ok<AGROW>
end
% S3: feed composition sweep at fixed T, P, and reference tie line.
for z=[0.25 0.375 0.5 0.625 0.75]
    c=cfg; c.feed.z=[z;1-z]; r=cps22_reference_flash(c,dataFile);
    rows(end+1)=rowFromRef('S3_FEED_COMPOSITION','z_ethanol',z,'mol/mol',c,r,'vapour_fraction',r.beta,'-', ...
        'Reference tie-line/phase-boundary classification; target model not used.'); %#ok<AGROW>
end
% S4: throughput scaling at a fixed empirical split.
base=cps22_reference_flash(cfg,dataFile);
for F=[50 75 100 125 150]
    c=cfg; c.feed.flow_kmol_h=F; r=base; r.F_kmol_h=F; r.L_kmol_h=(1-r.beta)*F; r.V_kmol_h=r.beta*F;
    rows(end+1)=rowFromRef('S4_FEED_FLOW','feed_flow_kmol_h',F,'kmol/h',c,r,'vapour_flow',r.V_kmol_h,'kmol/h', ...
        'Linear phase-flow scaling at fixed empirical tie-line; not a process-model sensitivity.'); %#ok<AGROW>
end
% S5: kij residual diagnostic evaluated on the empirical tie-line.
if strcmp(base.status,'TWO_PHASE_REFERENCE_INTERPOLATION')
    for kij=[-0.10 -0.05 0 0.05 0.10 0.15]
        try
            q=cps22_gamma_phi(cfg.conditions.temperature_K,cfg.conditions.pressure_Pa,base.x,base.y,cfg,kij);
            rms=sqrt(mean(q.log_fugacity_residual.^2)); status='DIAGNOSTIC_ONLY_PARAMETER_SET_NOT_ACCEPTED';
        catch ME
            rms=NaN; status=['FAILED: ' ME.identifier];
        end
        rows(end+1)=struct('study_id','S5_SRK_KIJ_DIAGNOSTIC','varied_variable','srk_kij', ...
            'varied_value',kij,'varied_unit','dimensionless','T_K',cfg.conditions.temperature_K, ...
            'P_Pa',cfg.conditions.pressure_Pa,'z_ethanol',cfg.feed.z(1),'feed_flow_kmol_h',cfg.feed.flow_kmol_h, ...
            'beta',NaN,'x_ethanol',base.x(1),'y_ethanol',base.y(1),'L_kmol_h',NaN,'V_kmol_h',NaN, ...
            'response_metric','RMS_log_fugacity_residual','response_value',rms,'response_unit','dimensionless', ...
            'status',status,'notes','Diagnostic only. NRTL candidate range and target model acceptance remain unresolved.'); %#ok<AGROW>
    end
else
    rows(end+1)=struct('study_id','S5_SRK_KIJ_DIAGNOSTIC','varied_variable','srk_kij','varied_value',NaN, ...
        'varied_unit','dimensionless','T_K',cfg.conditions.temperature_K,'P_Pa',cfg.conditions.pressure_Pa, ...
        'z_ethanol',cfg.feed.z(1),'feed_flow_kmol_h',cfg.feed.flow_kmol_h,'beta',NaN,'x_ethanol',NaN, ...
        'y_ethanol',NaN,'L_kmol_h',NaN,'V_kmol_h',NaN,'response_metric','RMS_log_fugacity_residual', ...
        'response_value',NaN,'response_unit','dimensionless','status','BLOCKED_NO_REFERENCE_TIELINE', ...
        'notes','Could not evaluate kij diagnostic because base reference tie-line is unavailable.');
end
S=struct2table(rows);
end

function r=rowFromRef(id,varName,val,unit,cfg,ref,metric,metricVal,metricUnit,notes)
r=struct('study_id',id,'varied_variable',varName,'varied_value',val,'varied_unit',unit, ...
    'T_K',cfg.conditions.temperature_K,'P_Pa',cfg.conditions.pressure_Pa,'z_ethanol',cfg.feed.z(1), ...
    'feed_flow_kmol_h',cfg.feed.flow_kmol_h,'beta',ref.beta,'x_ethanol',ref.x(1),'y_ethanol',ref.y(1), ...
    'L_kmol_h',ref.L_kmol_h,'V_kmol_h',ref.V_kmol_h,'response_metric',metric, ...
    'response_value',metricVal,'response_unit',metricUnit,'status',ref.status,'notes',notes);
end
