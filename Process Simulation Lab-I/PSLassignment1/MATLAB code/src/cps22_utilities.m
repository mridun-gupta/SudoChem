function out = cps22_utilities(energy, cfg)
% Utility consumption remains blocked until energy duty and utility specifications exist.
out=struct('status','BLOCKED_ENERGY_OR_UTILITY_BASIS','heating_duty_W',NaN, ...
    'cooling_duty_W',NaN,'utility_consumption',NaN,'utility_unit','not defined', ...
    'reason','No accepted enthalpy duty, utility supply/return conditions, temperature approach or efficiency is available.', ...
    'energy_status',energy.status,'utility_basis_accepted',cfg.engineering.utility_basis_accepted);
end
